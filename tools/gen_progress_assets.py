"""Encode supplied HUD landmarks without taking tiles away from surf actors.

The bottom raster uses signed BG addressing: tile IDs 0..8 live at 9000..908F,
outside the unsigned 8000..8FFF patterns used by the rest of the game.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PALE = (22, 27, 30)  # Match the existing progress strip, not a boxed PNG backdrop.
island = [(26,20,13), (28,24,17), (2,6,16), PALE]
flag = [(19,11,7), (0,0,0), (31,31,31), PALE]
patterns = []

def encode(values):
    return [b for y in range(8) for b in (
        sum((values[y*8+x]&1) << (7-x) for x in range(8)),
        sum(((values[y*8+x]>>1)&1) << (7-x) for x in range(8)))]

for name, colors in [
    ('progress_start', {(214,165,107):0, (230,197,140):1, (16,49,132):2, (173,214,239):3}),
    ('progress_finish', {(0,0,0):1, (255,255,255):2, (173,214,239):3}),
]:
    im = Image.open(ROOT/'gbc/art'/f'{name}.png').convert('RGBA')
    assert im.size == (16,16), f'{name}: expected supplied 16x16 pixels'
    assert all(p[3] == 255 for p in im.getdata()), f'{name}: unexpected transparency'
    for y in (0,8):
        for x in (0,8):
            patterns += encode([colors[im.getpixel((x+px,y+py))[:3]] for py in range(8) for px in range(8)])
# 8x8 beaver head: ears, fur, eyes and two buck teeth. Palette 0's previously
# unused color 0 is fur; the flag still uses only black, white and backdrop.
head = [".##..##.","#oo##oo#","#oooooo#","#o#oo#o#",
        "#oooooo#",".#o##o#.","..#WW#..","...##..."]
patterns += encode([{'o':0,'#':1,'W':2,'.':3}[p] for row in head for p in row])

def array(name, values):
    return f'static const uint8_t {name}[]={{\n'+',\n'.join(
        ','.join(f'0x{v:02x}' for v in values[i:i+16]) for i in range(0,len(values),16))+'\n};\n'

def rgb_bytes(colors):
    return [byte for r,g,b in colors for byte in (
        (r|(g<<5)|(b<<10))&255, (r|(g<<5)|(b<<10))>>8)]

# Derive the restoration colors from the current authored background palette.
bg = Image.open(ROOT/'gbc/res/bg.png')
palette = bg.getpalette()
assert palette is not None
original = [tuple(c>>3 for c in palette[i:i+3]) for p in (0,5) for i in range(p*12,p*12+12,3)]
text = '/* Generated by tools/gen_progress_assets.py. */\n'
text += array('progress_patterns', patterns)
text += array('progress_hud_palettes', rgb_bytes(flag+island))
text += array('progress_game_palettes', rgb_bytes(original))
(ROOT/'gbc/src/progress_data.h').write_text(text)
print('Progress: supplied island/finish icons and 8x8 beaver head; 9 signed BG patterns')
