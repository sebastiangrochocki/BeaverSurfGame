"""Emits gbc/src/song.h and gba/src/song.rs: one tune, two ports. Run from the repo root.

"Formosa Swell": a bright pentatonic tune in G (gong mode) with a dotted lilt, the kind of
melody a dizi would carry over a plucked yueqin and a walking bass. Original, not a quote.
"""
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')

NAMES = {'C': 0, 'D': 2, 'E': 4, 'F': 5, 'G': 7, 'A': 9, 'B': 11}


def midi(name):
    if name == '-':
        return 0
    sharp = '#' in name
    letter = name[0]
    octave = int(name[-1])
    return 12 * (octave + 1) + NAMES[letter] + (1 if sharp else 0)


def bar(spec):
    """'E5.2 D5.2 ...' -> [(midi, len)], asserting the bar holds 16 steps."""
    out = []
    for token in spec.split():
        note, length = token.split('.')
        out.append((midi(note), int(length)))
    assert sum(l for _, l in out) == 16, spec
    return out


# Melody, pulse 1. Twelve bars: A A B A'.
A1 = bar('E5.2 D5.2 B4.2 A4.2 G4.4 A4.2 B4.2')
A2 = bar('D5.4 B4.2 A4.2 G4.6 -.2')
A3 = bar('A4.2 B4.2 D5.2 E5.2 G5.4 E5.2 D5.2')
A4 = bar('B4.2 D5.2 A4.2 B4.2 A4.6 -.2')
B1 = bar('G5.3 G5.1 E5.2 D5.2 E5.4 D5.2 B4.2')
B2 = bar('A4.2 B4.2 D5.2 B4.2 A4.6 -.2')
B3 = bar('E5.3 E5.1 D5.2 B4.2 D5.4 E5.2 G5.2')
B4 = bar('A5.4 G5.2 E5.2 D5.6 -.2')
C3 = bar('E5.2 G5.2 E5.2 D5.2 B4.2 D5.2 A4.2 B4.2')
C4 = bar('A4.2 G4.2 E4.2 D4.2 G4.6 -.2')
MELODY = A1 + A2 + A3 + A4 + B1 + B2 + B3 + B4 + A1 + A2 + C3 + C4

# Chords per bar drive the chuck and bass lines.
CHORDS = ['G', 'G', 'C', 'D', 'C', 'G', 'Em', 'D', 'G', 'Em', 'C/D', 'G']

CHUCK = {  # off-beat plucks: (after beat 1, after beat 2, after 3, after 4)
    'G': 'B4 D5 B4 D5',
    'C': 'E5 C5 E5 C5',
    'D': 'F#4 A4 F#4 A4',
    'Em': 'G4 B4 G4 B4',
    'C/D': 'E5 C5 F#4 A4',
}
BASS = {  # quarter notes, sounding pitch
    'G': 'G2 D3 G2 D3',
    'C': 'C3 G2 C3 G2',
    'D': 'D3 A2 D3 A2',
    'Em': 'E2 B2 E2 B2',
    'C/D': 'C3 G2 D3 A2',
}

HARMONY = []
BASSLINE = []
for chord in CHORDS:
    HARMONY += bar(' '.join(f'-.2 {n}.2' for n in CHUCK[chord].split()))
    BASSLINE += bar(' '.join(f'{n}.4' for n in BASS[chord].split()))
# Final bar: bass lands on the root and stays.
BASSLINE[-4:] = bar('G2.4 D3.4 G2.8')

# Drums: 1 kick, 2 snare, 3 tick.
DRUM_BAR = [(1, 4), (3, 2), (3, 2), (2, 4), (3, 2), (3, 2)]
DRUMS = DRUM_BAR * 12

for name, track in [('MELODY', MELODY), ('HARMONY', HARMONY), ('BASSLINE', BASSLINE), ('DRUMS', DRUMS)]:
    assert sum(l for _, l in track) == 16 * 12, name

# Game Boy pulse frequency register for MIDI note m (C2..B6 -> index m - 36).
LOW, HIGH = 36, 96


def reg(m):
    f = 440.0 * 2 ** ((m - 69) / 12)
    return round(2048 - 131072 / f)


FREQS = [reg(m) for m in range(LOW, HIGH)]
assert all(0 <= r < 2048 for r in FREQS)
for m, _ in MELODY + HARMONY:
    assert m == 0 or LOW <= m < HIGH
for m, _ in BASSLINE:
    assert LOW <= m + 12 < HIGH  # the wave channel sounds an octave below the register

# Triangle for the wave channel: 32 four-bit samples packed two per byte, high nibble first.
tri = [i for i in range(16)] + [15 - i for i in range(16)]
WAVE = [(tri[i] << 4) | tri[i + 1] for i in range(0, 32, 2)]

HEAD = 'Generated by the song script; edit the bars there, not here. "Formosa Swell", a pentatonic tune in G.'


def c_pairs(track, per_line=8):
    lines = []
    for i in range(0, len(track), per_line):
        chunk = track[i:i + per_line]
        lines.append('    ' + ' '.join(f'{m:3d},{l:2d},' for m, l in chunk))
    return '\n'.join(lines)


c = f'''/* {HEAD} */
#ifndef BEAVER_SONG_H
#define BEAVER_SONG_H

#include <stdint.h>

/* Frames per sixteenth-note step: 7 is about 128 bpm. */
#define SONG_STEP_FRAMES 7
/* Pitch tables index MIDI note minus this; 0 in a track is a rest. */
#define SONG_LOW_NOTE {LOW}
#define SONG_NOTES {len(FREQS)}

/* Tracks are (note, steps) pairs; every track spans the same {16 * 12} steps and loops. */
static const uint8_t SONG_MELODY[] = {{
{c_pairs(MELODY)}
}};
static const uint8_t SONG_HARMONY[] = {{
{c_pairs(HARMONY)}
}};
/* Bass notes are the sounding pitch; the wave channel plays an octave below the register. */
static const uint8_t SONG_BASS[] = {{
{c_pairs(BASSLINE)}
}};
/* Drums: 1 kick, 2 snare, 3 tick. */
static const uint8_t SONG_DRUMS[] = {{
{c_pairs(DRUMS)}
}};

static const uint16_t SONG_FREQ[SONG_NOTES] = {{
{chr(10).join('    ' + ' '.join(f'{r:4d},' for r in FREQS[i:i + 12]) for i in range(0, len(FREQS), 12))}
}};

static const uint8_t SONG_WAVE[16] = {{
    {' '.join(f'0x{b:02X},' for b in WAVE)}
}};

#endif
'''

open(os.path.join(ROOT, 'gbc/src/song.h'), 'w').write(c)


def rs_pairs(track, per_line=8):
    lines = []
    for i in range(0, len(track), per_line):
        chunk = track[i:i + per_line]
        lines.append('    ' + ' '.join(f'({m}, {l}),' for m, l in chunk))
    return '\n'.join(lines)


rs = f'''//! {HEAD}

/// Frames per sixteenth-note step: 7 is about 128 bpm.
pub const STEP_FRAMES: u8 = 7;
/// Pitch tables index MIDI note minus this; 0 in a track is a rest.
pub const LOW_NOTE: u8 = {LOW};

/// Tracks are (note, steps) pairs; every track spans the same {16 * 12} steps and loops.
pub const MELODY: &[(u8, u8)] = &[
{rs_pairs(MELODY)}
];
pub const HARMONY: &[(u8, u8)] = &[
{rs_pairs(HARMONY)}
];
/// Bass notes are the sounding pitch; the wave channel plays an octave below the register.
pub const BASS: &[(u8, u8)] = &[
{rs_pairs(BASSLINE)}
];
/// Drums: 1 kick, 2 snare, 3 tick.
pub const DRUMS: &[(u8, u8)] = &[
{rs_pairs(DRUMS)}
];

pub const FREQ: [u16; {len(FREQS)}] = [
{chr(10).join('    ' + ' '.join(f'{r},' for r in FREQS[i:i + 12]) for i in range(0, len(FREQS), 12))}
];

pub const WAVE: [u8; 16] = [{', '.join(f'0x{b:02X}' for b in WAVE)}];
'''
open(os.path.join(ROOT, 'gba/src/song.rs'), 'w').write(rs)
print('ok', len(MELODY), len(HARMONY), len(BASSLINE), len(DRUMS))
