"""Convert supplied beach pixels and carrying poses to native GBC 2bpp."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'gbc/res'

def encode(pixels, width, x, y):
    out = []
    for py in range(8):
        lo = hi = 0
        for px in range(8):
            v = pixels[(y+py)*width+x+px]
            lo |= (v & 1) << (7-px)
            hi |= ((v >> 1) & 1) << (7-px)
        out.extend([lo,hi])
    return out

def sprite(pixels,w,h):
    return [b for y in range(0,h,16) for x in range(0,w,8)
            for half in (0,8) for b in encode(pixels,w,x,y+half)]

tiles=[]
for name,key in [('sand',{(230,197,140):0,(214,165,107):2}),
                 ('water',{(16,49,132):0,(41,107,189):1,(99,173,222):2}),
                 ('shoreline',{(230,197,140):0,(16,49,132):1,(214,165,107):2,(173,214,239):3})]:
    im=Image.open(RES/'beach'/f'{name}.png').convert('RGB')
    pixels=[key[c] for c in im.getdata()]
    for y in range(0,im.height,8):
        for x in range(0,im.width,8):tiles.extend(encode(pixels,im.width,x,y))
assert len(tiles)==9*16

walking=[]
back_second=[]
front_second=[]
for name in ['walk_0','walk_1','walk_front','walk_back','walk_back_1','walk_front_1']:
    art=Image.open(ROOT/'gbc/art'/f'{name}.png').convert('RGBA')
    assert art.size==(32,32)
    key={(0,0,0):1,(156,90,58):2,(156,0,49):3}
    pixels=[0 if c[3]==0 else key[c[:3]] for c in art.getdata()]
    if name=='walk_back_1': back_second=sprite(pixels,32,32)
    elif name=='walk_front_1': front_second=sprite(pixels,32,32)
    else: walking.extend(sprite(pixels,32,32))
# Preserve the reserved VRAM swap size. The carried board is already in each pose.
assert len(walking)==64*16

def array(name,values):
    rows=[','.join(f'0x{v:02x}' for v in values[i:i+16]) for i in range(0,len(values),16)]
    return f'static const uint8_t {name}[] = {{\n    '+',\n    '.join(rows)+'\n};\n'

(ROOT/'gbc/src/beach_data.h').write_text('/* Generated by tools/gen_beach_assets.py. */\n'+array('beach_patterns',tiles)+array('beach_actors',walking)+array('beach_back_second',back_second)+array('beach_front_second',front_second))
print('Beach: 9 background patterns; 6 carrying poses, 64 VRAM patterns with streamed front/back walking')
