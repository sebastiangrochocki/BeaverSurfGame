#!/usr/bin/env python3
"""Exact 1024-tick wave refresh cycle in ROM banks 8..25 (32 bytes/tick).

The SM83 spends much of its frame multiplying the same periodic wave terms.
Cache only the 16 entries sea_refresh updates, preserving the four-tick cadence.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def array(source, name):
    body = re.search(r'\b' + name + r'\[\d+\]\s*=\s*\{(.*?)\};', source, re.S)[1]
    return [int(x) for x in re.findall(r'-?\d+', body)]

def tables():
    source = (ROOT/'gbc/src/wave_tables.h').read_text()
    env = array(source, 'ENV_AMP')
    lift = array(source, 'ENV_LIFT')
    amp1, amp2 = array(source, 'AMP1_TAB'), array(source, 'AMP2_TAB')
    sine = array((ROOT/'gbc/src/wave.c').read_text(), 'SIN8')
    for tier in range(9):
        data = bytearray()
        for tick in range(1024):
            for i in range(tick & 3, 64, 4):
                phase = (i*8+(tick >> 1)) & 511
                amplitude = env[phase] & 255
                value = (7168 + lift[phase]
                         + ((amp1[tier*256+amplitude]*sine[(i*8+tick)&255]) >> 2)
                         + ((amp2[tier*256+amplitude]*sine[(i*16+tick*2)&255]) >> 2)
                         + ((6*sine[(i*4+tick)&255]) >> 2))
                data.extend(value.to_bytes(2, 'little', signed=True))
        yield data

def main():
    dest = ROOT/'gbc/build/gen'
    dest.mkdir(parents=True, exist_ok=True)
    for tier, data in enumerate(tables()):
        for half in range(2):
            bank = 8+tier*2+half
            chunk = data[half*16384:(half+1)*16384]
            lines = ['/* Generated by tools/gen_wave_runtime.py. */', f'#pragma bank {bank}',
                     f'const unsigned char wave_bank_{bank}[16384] = {{']
            lines += ['    '+','.join(str(x) for x in chunk[i:i+32])+',' for i in range(0,len(chunk),32)]
            lines.append('};\n')
            (dest/f'wave{bank}.c').write_text('\n'.join(lines))

if __name__ == '__main__':
    main()
