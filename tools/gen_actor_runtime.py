"""Generate native collision masks and precomposited body/deck lower rows."""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / 'gbc/res'
ART = ROOT / 'gbc/art'

def rgba(name):
    im = Image.open(ART/name).convert('RGBA')
    return [p[3] != 0 for p in im.getdata()]

def sheet(name, frame, w, h):
    im = Image.open(RES/name)
    return [im.getpixel((frame*w+x,y)) & 3 for y in range(h) for x in range(w)]

def encode(pixels,w=32):
    out=[]
    for x in range(0,w,8):
        for y in range(16):
            lo=hi=0
            for px in range(8):
                v=pixels[y*w+x+px]
                lo|=(v&1)<<(7-px);hi|=((v>>1)&1)<<(7-px)
            out.extend((lo,hi))
    return out

def mask(pixels,w,h,fill=False):
    rows=[0]*(h*4)
    for y in range(h):
        xs=[x for x in range(w) if pixels[y*w+x]]
        if fill and xs: xs=range(min(xs),max(xs)+1)
        for x in xs: rows[y*4+x//8]|=1<<(x%8)
    xy=[(x,y) for y in range(h) for x in range(w) if rows[y*4+x//8] & (1<<(x%8))]
    bounds=[min(x for x,y in xy),min(y for x,y in xy),max(x for x,y in xy)+1,max(y for x,y in xy)+1]
    return rows,bounds

def array(name, data):
    return 'static const uint8_t '+name+'[] = {\n'+''.join('    '+','.join(str(v) for v in data[i:i+24])+',\n' for i in range(0,len(data),24))+'};\n'

lower=[]
for frame in range(7):
    body=sheet('beaver.png',frame,32,32)[512:]
    for deck in range(3):
        board=sheet('board.png',deck,32,16)
        lower.extend(encode([a or b for a,b in zip(body,board)]))
for deck in range(3): lower.extend(encode(sheet('board.png',deck,32,16)))

jump=rgba('jump.png')
body=[rgba('surf.png'),rgba('tug.png'),jump,jump,[jump[x*32+31-y] for y in range(32) for x in range(32)],rgba('left.png'),rgba('right.png')]
body_masks=[];body_bounds=[]
for pixels in body:
    m,b=mask(pixels,32,32);body_masks.extend(m);body_bounds.extend(b)
targets=[];target_bounds=[]
for frame in range(3):
    m,b=mask(sheet('gull.png',frame,32,16),32,16);targets.extend(m+[0]*64);target_bounds.extend(b)
m,b=mask(sheet('heart.png',0,16,16),16,16);targets.extend(m+[0]*64);target_bounds.extend(b)
# The hoop opening is a pickup target too, not just its opaque rim.
m,b=mask(sheet('ring.png',0,16,16),16,16,fill=True);targets.extend(m+[0]*64);target_bounds.extend(b)
race_gulls=[]
for frame in range(3):
    source=sheet('gull.png',frame,32,16)
    compact=[max(source[y*32+x*2:y*32+x*2+2]) for y in range(16) for x in range(16)]
    race_gulls.extend(encode(compact,16))
    m,b=mask(compact,16,16);targets.extend(m+[0]*64);target_bounds.extend(b)
out=array('actor_lower',lower)+array('actor_body_masks',body_masks)+array('actor_body_bounds',body_bounds)+array('actor_target_masks',targets)+array('actor_target_bounds',target_bounds)+array('actor_race_gulls',race_gulls)
(ROOT/'gbc/src/actor_data.h').write_text('/* Generated by tools/gen_actor_runtime.py. */\n'+out)
print('Actor runtime: 24 lower-row variants; transparent-pixel body and pickup masks')
