//! Writes gbc/src/wave_tables.h: lookup tables for the Game Boy port, so it never multiplies or
//! divides where the Rust rules do. Every value comes from the same formulas the Rust rules use,
//! and the golden traces verify the port end to end.
//!
//! Run from the repository root: `cargo run --manifest-path sim/Cargo.toml --bin gen_wave_tables`

use std::fmt::Write as _;
use std::fs;
use std::path::Path;

use beaver_sim::envelope_cell;

fn main() {
    let mut amp = Vec::with_capacity(512);
    let mut lift = Vec::with_capacity(512);
    let mut lift3 = Vec::with_capacity(512);
    for cell in 0..16u8 {
        for frac in 0..32u8 {
            let (a, l) = envelope_cell(cell, frac);
            let delta = a - 256;
            assert!((-128..=127).contains(&delta), "amp delta {delta} out of i8");
            amp.push(delta as i8);
            lift.push(l);
            lift3.push(l / 3);
        }
    }
    // Amplitudes per tier for every envelope delta, indexed by the delta as a byte:
    // (base * amp_mod) >> 8 and (base2 * (amp_mod + 256)) >> 9 as in table_entry.
    let mut amp1_tab = Vec::with_capacity(9 * 256);
    let mut amp2_tab = Vec::with_capacity(9 * 256);
    for tier in 0..9u8 {
        let base1 = beaver_sim::amplitude_half(tier);
        let base2 = 6 + 2 * tier as u16;
        for byte in 0..=255u8 {
            let delta = byte as i8 as i16;
            let amp_mod = (256 + delta) as u16;
            let amp1 = (base1 * amp_mod) >> 8;
            let amp2 = (base2 * (amp_mod + 256)) >> 9;
            assert!(amp1 <= 127 && amp2 <= 127);
            amp1_tab.push(amp1 as i8);
            amp2_tab.push(amp2 as i8);
        }
    }
    // Jump-meter positions: see Sea::jump_meter.
    let climb: Vec<u8> = (0..=256i16).map(|c| (c * 32 / 204).min(31) as u8).collect();
    let top: Vec<u8> = (0..=52i16)
        .map(|t| (32 + (t * 32 / 52).min(31)) as u8)
        .collect();
    let descent: Vec<u8> = (0..=256i16).map(|d| (64 + d * 32 / 257) as u8).collect();

    let mut out = String::new();
    writeln!(
        out,
        "/* Generated by sim/src/bin/gen_wave_tables.rs. Do not edit. */"
    )
    .unwrap();
    writeln!(out, "#ifndef BEAVER_WAVE_TABLES_H").unwrap();
    writeln!(out, "#define BEAVER_WAVE_TABLES_H").unwrap();
    writeln!(out, "#include <stdint.h>").unwrap();
    table(
        &mut out,
        "Envelope amplitude scale minus 256, indexed by cell * 32 + pixel.",
        "int8_t",
        "ENV_AMP",
        &amp,
    );
    table(
        &mut out,
        "Envelope lift in Q10.6, indexed by cell * 32 + pixel.",
        "int16_t",
        "ENV_LIFT",
        &lift,
    );
    table(
        &mut out,
        "ENV_LIFT / 3, truncated toward zero, for the front wave.",
        "int16_t",
        "ENV_LIFT3",
        &lift3,
    );
    table(
        &mut out,
        "Main swell amplitude per tier, indexed by tier * 256 + (uint8_t)delta.",
        "int8_t",
        "AMP1_TAB",
        &amp1_tab,
    );
    table(
        &mut out,
        "Secondary swell amplitude per tier, indexed by tier * 256 + (uint8_t)delta.",
        "int8_t",
        "AMP2_TAB",
        &amp2_tab,
    );
    table(
        &mut out,
        "Meter position for climb progress 0..=256 below the green window.",
        "uint8_t",
        "METER_CLIMB",
        &climb,
    );
    table(
        &mut out,
        "Meter position for climb progress minus 204, 0..=52, inside the green window.",
        "uint8_t",
        "METER_TOP",
        &top,
    );
    table(
        &mut out,
        "Meter position for descent progress 0..=256 past the crest.",
        "uint8_t",
        "METER_DESCENT",
        &descent,
    );
    writeln!(out, "\n#endif").unwrap();

    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("../gbc/src/wave_tables.h");
    fs::write(&path, out).expect("write wave_tables.h");
    println!("wrote {}", path.display());
}

fn table<T: std::fmt::Display>(out: &mut String, doc: &str, ty: &str, name: &str, values: &[T]) {
    writeln!(out, "\n/* {doc} */").unwrap();
    writeln!(out, "static const {ty} {name}[{}] = {{", values.len()).unwrap();
    let strings: Vec<String> = values.iter().map(|v| v.to_string()).collect();
    for row in strings.chunks(16) {
        writeln!(out, "    {},", row.join(", ")).unwrap();
    }
    writeln!(out, "}};").unwrap();
}
